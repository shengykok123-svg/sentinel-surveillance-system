"""
Recognition-event repository module for Sentinel.

Manages persistence of detection and recognition events generated by
the video-analysis pipeline.  Each event records that a face was
detected (and optionally recognised) in a specific camera frame, along
with its bounding box, similarity score, and associated track.

Tracks represent the lifecycle of a single subject across consecutive
frames (powered by DeepSORT or a similar tracker).  The repository
creates new tracks when a track ID is first observed and updates
existing tracks with new positions, maintaining the last 50 trajectory
points for spatial history.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import datetime, timezone

from sqlalchemy import delete, desc, func, select

from app.core.database import DatabaseManager
from app.models.entities import CameraEntity, DetectionEventEntity, PersonEntity, TrackDetectionEventEntity, TrackEntity


@dataclass(slots=True)
class EventRow:
    """Lightweight data-transfer object returned by event queries.

    Flattens the joined result of a detection event together with its
    related camera, person, and track information into a single
    object that can be serialised for API responses.

    Attributes:
        id: Unique identifier of the detection event.
        camera_id: UUID of the camera that captured the event.
        camera_name: Human-readable camera name.
        person_id: UUID of the recognised person, or ``None`` if
            the subject is unknown.
        person_name: Display name of the recognised person, or
            ``None``.
        person_type: Classification of the recognised person
            (e.g. ``"staff"``, ``"watchlist"``), or ``None``.
        similarity: Cosine-similarity score between the detected
            face and the matched embedding, or ``None`` if
            unrecognised.
        track_id: Integer DeepSORT track identifier, or ``None``.
        status: Either ``"recognized"`` or ``"unknown"``.
        bbox: Bounding box as ``[x1, y1, x2, y2]``, or ``None``.
        timestamp: UTC datetime when the detection occurred.
        event_type: Human-readable event label such as
            ``"POI recognized"``, ``"Person recognized"``, or
            ``"Unknown person detected"``.
    """
    id: str
    camera_id: str
    camera_name: str
    person_id: str | None
    person_name: str | None
    person_type: str | None
    similarity: float | None
    track_id: int | None
    status: str
    bbox: list[int] | None
    timestamp: datetime
    event_type: str
    snapshot_path: str | None = None
    snapshot_width: int | None = None
    snapshot_height: int | None = None


class RecognitionEventRepository:
    """Repository handling persistence for detection events and tracks.

    All public methods open their own database sessions via the
    injected ``DatabaseManager``.
    """

    def __init__(self, database: DatabaseManager) -> None:
        """Initialise the repository with a database manager.

        Args:
            database: The ``DatabaseManager`` instance used to obtain
                database sessions.
        """
        self.database = database

    def add(self, **payload) -> EventRow:
        """Record a new detection/recognition event and update tracking state.

        This method performs several operations within a single
        database transaction:

        1. Validates that the referenced camera exists.
        2. Finds or creates a ``TrackEntity`` for the given camera +
           DeepSORT track ID combination.
        3. Updates the track's trajectory history (capped at 50
           entries).
        4. Creates a ``DetectionEventEntity`` with bounding-box and
           confidence data.
        5. Links the event to the track via
           ``TrackDetectionEventEntity``.

        Args:
            **payload: Keyword arguments containing event data:
                - ``camera_id`` (str): UUID of the camera (required).
                - ``person_id`` (str | None): UUID of the recognised
                  person, or ``None`` for unknown detections.
                - ``track_id`` (int): DeepSORT tracker ID (required).
                - ``bbox`` (list[int] | None): Bounding box as
                  ``[x1, y1, x2, y2]``; defaults to ``[0, 0, 1, 1]``.
                - ``similarity`` (float | None): Cosine similarity.
                - ``detection_confidence`` (float | None): Detector
                  confidence score.

        Returns:
            An ``EventRow`` summarising the persisted event.

        Raises:
            ValueError: If the specified camera does not exist.
        """
        camera_uuid = uuid.UUID(str(payload["camera_id"]))
        person_uuid = uuid.UUID(str(payload["person_id"])) if payload.get("person_id") else None
        track_number = int(payload["track_id"])
        bbox = payload.get("bbox") or [0, 0, 1, 1]
        similarity = payload.get("similarity")
        detection_confidence = payload.get("detection_confidence")
        now = datetime.now(timezone.utc)

        with self.database.session() as session:
            # Ensure the camera exists before recording any event
            camera = session.get(CameraEntity, camera_uuid)
            if camera is None:
                raise ValueError(f"Camera '{payload['camera_id']}' does not exist")

            # Look up an existing track for this camera + DeepSORT ID
            track = session.scalar(
                select(TrackEntity).where(
                    TrackEntity.camera_id == camera_uuid,
                    TrackEntity.deepsort_track_id == track_number,
                )
            )

            # Tracks are "confirmed" when linked to a known person
            status = "confirmed" if person_uuid else "tentative"

            # Build a single-point trajectory entry from the bounding box
            trajectory = [{"x": bbox[0], "y": bbox[1], "w": max(bbox[2] - bbox[0], 1), "h": max(bbox[3] - bbox[1], 1)}]

            if track is None:
                # First time seeing this track ID on this camera -- create a new track
                track = TrackEntity(
                    person_id=person_uuid,
                    camera_id=camera_uuid,
                    deepsort_track_id=track_number,
                    status=status,
                    started_at=now,
                    last_seen_at=now,
                    frame_count=1,
                    trajectory=trajectory,
                )
                session.add(track)
                session.flush()
            else:
                # Update the existing track with the latest observation
                track.person_id = person_uuid or track.person_id
                track.status = status
                track.last_seen_at = now
                track.frame_count += 1
                # Append the new position and cap the history at 50 entries
                # to prevent unbounded growth of the trajectory JSON.
                history = list(track.trajectory or [])
                history.extend(trajectory)
                track.trajectory = history[-50:]
                session.add(track)

            # Create the detection event record.
            # A confidence_score of -1.0 is used as a sentinel to
            # indicate that no similarity score was available.
            event = DetectionEventEntity(
                camera_id=camera_uuid,
                person_id=person_uuid,
                confidence_score=-1.0 if similarity is None else float(max(min(similarity, 1.0), 0.0)),
                detection_confidence=float(
                    max(min(detection_confidence if detection_confidence is not None else (similarity if similarity is not None else 0.0), 1.0), 0.0)
                ),
                bbox_x=int(bbox[0]),
                bbox_y=int(bbox[1]),
                bbox_w=max(int(bbox[2] - bbox[0]), 1),
                bbox_h=max(int(bbox[3] - bbox[1]), 1),
                snapshot_path=payload.get("snapshot_path"),
                snapshot_width=payload.get("snapshot_width"),
                snapshot_height=payload.get("snapshot_height"),
                detected_at=now,
            )
            session.add(event)
            session.flush()

            # Create the many-to-many link between track and event
            link = TrackDetectionEventEntity(track_id=track.id, event_id=event.id, event_time=event.detected_at)
            session.add(link)
            session.flush()

            # Resolve person details for the response DTO
            person_name = None
            person_type = None
            if person_uuid is not None:
                person = session.get(PersonEntity, person_uuid)
                person_name = person.full_name if person is not None else None
                person_type = person.person_type if person is not None else None

            # Determine a human-readable event-type label based on
            # whether a person was recognised and their classification
            event_type = (
                "POI recognized"
                if person_uuid is not None and person_type == "watchlist"
                else "Person recognized"
                if person_uuid is not None
                else "Unknown person detected"
            )

            return EventRow(
                id=str(event.id),
                camera_id=str(camera.id),
                camera_name=camera.name,
                person_id=str(person_uuid) if person_uuid else None,
                person_name=person_name,
                person_type=person_type,
                similarity=similarity if similarity is not None else None,
                track_id=track.deepsort_track_id,
                status="recognized" if person_uuid else "unknown",
                bbox=[event.bbox_x, event.bbox_y, event.bbox_x + event.bbox_w, event.bbox_y + event.bbox_h],
                timestamp=event.detected_at,
                event_type=event_type,
                snapshot_path=event.snapshot_path,
                snapshot_width=event.snapshot_width,
                snapshot_height=event.snapshot_height,
            )

    def list(
        self,
        limit: int = 50,
        offset: int = 0,
        *,
        recognized_only: bool = False,
    ) -> tuple[int, list[EventRow]]:
        """Return a paginated list of detection events.

        Events are returned in reverse chronological order (newest
        first).  Each event is joined with its related camera, person,
        and track to populate the full ``EventRow`` DTO.

        Args:
            limit: Maximum number of events to return (default 50).
            offset: Number of events to skip for pagination
                (default 0).

        Returns:
            A ``(total_count, events)`` tuple where *total_count* is
            the overall number of events in the database and *events*
            is the page of ``EventRow`` objects.
        """
        with self.database.session() as session:
            # Get the total event count for pagination metadata
            count_stmt = select(func.count()).select_from(DetectionEventEntity)
            if recognized_only:
                count_stmt = count_stmt.where(DetectionEventEntity.person_id.is_not(None))
            total = int(session.scalar(count_stmt) or 0)

            stmt = (
                select(
                    DetectionEventEntity,
                    CameraEntity.name,
                    PersonEntity.full_name,
                    PersonEntity.person_type,
                    TrackEntity.deepsort_track_id,
                )
                .join(CameraEntity, CameraEntity.id == DetectionEventEntity.camera_id)
                .outerjoin(PersonEntity, PersonEntity.id == DetectionEventEntity.person_id)
                .outerjoin(
                    TrackDetectionEventEntity,
                    # Match on both event ID and timestamp to ensure
                    # the correct link row is joined when composite
                    # keys are in use.
                    (TrackDetectionEventEntity.event_id == DetectionEventEntity.id)
                    & (TrackDetectionEventEntity.event_time == DetectionEventEntity.detected_at),
                )
                .outerjoin(TrackEntity, TrackEntity.id == TrackDetectionEventEntity.track_id)
                .order_by(desc(DetectionEventEntity.detected_at))
                .offset(offset)
                .limit(limit)
            )
            if recognized_only:
                stmt = stmt.where(DetectionEventEntity.person_id.is_not(None))
            rows = session.execute(stmt).all()
            return total, [
                EventRow(
                    id=str(event.id),
                    camera_id=str(event.camera_id),
                    camera_name=camera_name,
                    person_id=str(event.person_id) if event.person_id else None,
                    person_name=person_name,
                    person_type=person_type,
                    # A stored confidence_score of -1.0 means "no
                    # similarity was available" -- map it back to None.
                    similarity=None if event.confidence_score < 0 else event.confidence_score,
                    track_id=track_id,
                    status="recognized" if event.person_id else "unknown",
                    bbox=[event.bbox_x, event.bbox_y, event.bbox_x + event.bbox_w, event.bbox_y + event.bbox_h],
                    timestamp=event.detected_at,
                    event_type=(
                        "POI recognized"
                        if event.person_id and person_type == "watchlist"
                        else "Person recognized"
                        if event.person_id
                        else "Unknown person detected"
                    ),
                    snapshot_path=event.snapshot_path,
                    snapshot_width=event.snapshot_width,
                    snapshot_height=event.snapshot_height,
                )
                for event, camera_name, person_name, person_type, track_id in rows
            ]

    def snapshot_path_for_event(self, event_id: str) -> str | None:
        """Return the locally stored evidence image path for one event."""
        try:
            event_uuid = uuid.UUID(event_id)
        except (TypeError, ValueError):
            return None
        with self.database.session() as session:
            return session.scalar(
                select(DetectionEventEntity.snapshot_path).where(DetectionEventEntity.id == event_uuid)
            )

    def snapshot_paths(self) -> list[str]:
        """Return all image paths before a bulk event deletion."""
        with self.database.session() as session:
            return list(
                session.scalars(
                    select(DetectionEventEntity.snapshot_path).where(DetectionEventEntity.snapshot_path.is_not(None))
                )
            )

    def latest_for_person(
        self,
        *,
        person_ids: Iterable[str | uuid.UUID] | None = None,
    ) -> dict[str, EventRow]:
        """Return the single most recent event for each recognised person.

        A ``ROW_NUMBER()`` window ranks each person's events newest first
        (the event ID breaks ties on ``detected_at``), so the database
        returns one event per person instead of the whole history.

        Args:
            person_ids: Only look up these persons.  ``None`` (the
                default) covers everyone; an empty iterable returns an
                empty dictionary without querying.

        Returns:
            A dictionary mapping person-ID strings to their most recent
            ``EventRow``.
        """
        ranked = select(
            DetectionEventEntity.id.label("event_id"),
            DetectionEventEntity.detected_at.label("detected_at"),
            func.row_number()
            .over(
                partition_by=DetectionEventEntity.person_id,
                order_by=(desc(DetectionEventEntity.detected_at), desc(DetectionEventEntity.id)),
            )
            .label("recency_rank"),
        ).where(DetectionEventEntity.person_id.is_not(None))
        if person_ids is not None:
            wanted: dict[uuid.UUID, None] = {}
            for value in person_ids:
                try:
                    wanted[uuid.UUID(str(value))] = None
                except ValueError:
                    # Not a UUID, so it cannot match any stored person
                    continue
            if not wanted:
                return {}
            ranked = ranked.where(DetectionEventEntity.person_id.in_(list(wanted)))
        ranked = ranked.subquery()

        with self.database.session() as session:
            stmt = (
                select(
                    DetectionEventEntity,
                    CameraEntity.name,
                    PersonEntity.full_name,
                    PersonEntity.person_type,
                    TrackEntity.deepsort_track_id,
                )
                # Keep only each person's top-ranked event; the composite key
                # (id, detected_at) matches the partitioned table's primary key.
                .join(
                    ranked,
                    (ranked.c.event_id == DetectionEventEntity.id)
                    & (ranked.c.detected_at == DetectionEventEntity.detected_at),
                )
                .join(CameraEntity, CameraEntity.id == DetectionEventEntity.camera_id)
                # Inner join: only events linked to a known person
                .join(PersonEntity, PersonEntity.id == DetectionEventEntity.person_id)
                .outerjoin(
                    TrackDetectionEventEntity,
                    (TrackDetectionEventEntity.event_id == DetectionEventEntity.id)
                    & (TrackDetectionEventEntity.event_time == DetectionEventEntity.detected_at),
                )
                .outerjoin(TrackEntity, TrackEntity.id == TrackDetectionEventEntity.track_id)
                .where(ranked.c.recency_rank == 1)
                .order_by(desc(DetectionEventEntity.detected_at))
            )
            results: dict[str, EventRow] = {}
            for event, camera_name, person_name, person_type, track_id in session.execute(stmt):
                person_id = str(event.person_id)
                # An event linked to several tracks comes back once per track;
                # keep the first row so each person still maps to one event.
                if person_id in results:
                    continue
                results[person_id] = EventRow(
                    id=str(event.id),
                    camera_id=str(event.camera_id),
                    camera_name=camera_name,
                    person_id=person_id,
                    person_name=person_name,
                    person_type=person_type,
                    similarity=None if event.confidence_score < 0 else event.confidence_score,
                    track_id=track_id,
                    status="recognized",
                    bbox=[event.bbox_x, event.bbox_y, event.bbox_x + event.bbox_w, event.bbox_y + event.bbox_h],
                    timestamp=event.detected_at,
                    event_type="POI recognized" if person_type == "watchlist" else "Person recognized",
                )
            return results

    def clear(self) -> int:
        """Delete all detection events and their track links.

        This is a hard-delete used for bulk cleanup (e.g. during
        testing or system reset).  Track-detection links are removed
        first to satisfy foreign-key constraints.

        Returns:
            The total number of detection events that were deleted.
        """
        with self.database.session() as session:
            total = int(session.scalar(select(func.count()).select_from(DetectionEventEntity)) or 0)
            if total == 0:
                return 0
            # Delete links first to honour foreign-key constraints
            session.execute(delete(TrackDetectionEventEntity))
            session.execute(delete(DetectionEventEntity))
            return total
